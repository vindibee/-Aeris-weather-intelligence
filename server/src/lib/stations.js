/**
 * Равномерная сетка по обитаемым и наблюдаемым широтам — чтобы экстремум
 * не оказался «где-то между станциями» из списков выше.
 */
const GRID = (() => {
  /** @type {Station[]} */
  const out = [];
  for (let lat = -60; lat <= 75; lat += 15) {
    for (let lon = -180; lon < 180; lon += 40) {
      out.push({
        name: `${Math.abs(lat)}°${lat >= 0 ? 'с' : 'ю'} ${Math.abs(lon)}°${lon >= 0 ? 'в' : 'з'}`,
        country: 'сетка',
        lat,
        lon,
        tags: ['grid'],
      });
    }
  }
  return out;
})();

/** Полный набор точек для сканирования. */
export const STATIONS = [...HOT_SPOTS, ...COLD_SPOTS, ...WIND_SPOTS, ...GRID];

/** Точки, релевантные конкретному виду экстремума (плюс общая сетка). */
export function stationsFor(kind) {
  const named =
    kind === 'hot' ? HOT_SPOTS :
    kind === 'cold' ? COLD_SPOTS :
    WIND_SPOTS;
  // сетку добавляем всегда: она ловит то, чего нет в именном списке
  return [...named, ...GRID];
}
